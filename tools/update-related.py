#!/usr/bin/env python3
"""Regenerate the auto "Related" block at the end of DOCS notes.

Notes that share a `pr` or `issue` number in their frontmatter get links to
each other. The block is fully owned by this script (between the marker
comment and end of file) — re-running replaces it. GitHub-bound notes
(pr-description, issue, issue-comment) never get a block, because their body
is pasted into GitHub; they are still reachable through the other notes'
blocks. Run from anywhere:  python3 DOCS/tools/update-related.py
"""
import os, re, collections
import yaml

DOCS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = {"ai-dev-tasks", ".git", ".obsidian", "claude-config", "temp-files", "templates", "bases"}
NO_BLOCK_TYPES = {"pr-description", "issue", "issue-comment", "index", "registry", "kb", "tool-notes"}
AUTO_INDEX_DIRS = ("issues", "pr-descriptions")  # folders whose README gets an auto file list
INDEX_MARKER = "<!-- index:auto — file list generated by tools/update-related.py; do not edit by hand -->"
MARKER = "<!-- related:auto — generated from pr/issue properties by tools/update-related.py; do not edit by hand -->"

def load():
    notes = {}
    for r, ds, fs in os.walk(DOCS):
        ds[:] = [d for d in ds if d not in SKIP_DIRS]
        for f in fs:
            if f.endswith(".md") and f != "CLAUDE.md":
                p = os.path.join(r, f)
                t = open(p, encoding="utf-8").read()
                fm = {}
                if t.startswith("---\n"):
                    end = t.find("\n---\n", 4)
                    fm = yaml.safe_load(t[4:end]) or {}
                notes[p] = (t, fm)
    return notes

def main():
    notes = load()
    groups = collections.defaultdict(set)
    for p, (_, fm) in notes.items():
        if fm.get("type") in ("index", "registry", "kb", "tool-notes"):
            continue
        for k in ("pr", "issue"):
            for n in fm.get(k) or []:
                groups[(k, n)].add(p)
    related = collections.defaultdict(set)
    for ps in groups.values():
        for a in ps:
            related[a] |= ps - {a}
    changed = 0
    for p, (t, fm) in notes.items():
        wants = fm.get("type") not in NO_BLOCK_TYPES and bool(related.get(p))
        if not wants and MARKER not in t:
            continue
        body = t.split("\n" + MARKER)[0].rstrip("\n") + "\n"
        if wants:
            items = sorted(related[p], key=lambda q: (str(notes[q][1].get("date") or ""), q))
            lines = ["", MARKER, "## Related", ""]
            for q in items:
                qfm = notes[q][1]
                rel = os.path.relpath(q, os.path.dirname(p))
                name = os.path.splitext(os.path.basename(q))[0]
                meta = " · ".join(str(x) for x in (qfm.get("type"), qfm.get("date")) if x)
                lines.append(f"- {meta} · [{name}]({rel})")
            new = body + "\n".join(lines) + "\n"
        else:
            new = body
        if new != t:
            open(p, "w", encoding="utf-8").write(new)
            changed += 1
    for d in AUTO_INDEX_DIRS:
        readme = os.path.join(DOCS, d, "README.md")
        if readme not in notes:
            continue
        t = notes[readme][0]
        body = t.split("\n" + INDEX_MARKER)[0].rstrip("\n") + "\n"
        items = sorted((q for q in notes if os.path.dirname(q) == os.path.join(DOCS, d) and q != readme),
                       key=lambda q: (str(notes[q][1].get("date") or ""), q), reverse=True)
        lines = ["", INDEX_MARKER, "## Notes in this folder", ""]
        for q in items:
            qfm = notes[q][1]
            nums = " ".join([f"PR #{n}" for n in qfm.get("pr") or []] + [f"issue #{n}" for n in qfm.get("issue") or []])
            meta = " · ".join(str(x) for x in (qfm.get("date"), nums) if x)
            lines.append(f"- [{os.path.splitext(os.path.basename(q))[0]}](./{os.path.basename(q)})" + (f" — {meta}" if meta else ""))
        new = body + "\n".join(lines) + "\n"
        if new != t:
            open(readme, "w", encoding="utf-8").write(new)
            changed += 1
    print(f"related blocks / auto indexes updated in {changed} notes")

if __name__ == "__main__":
    main()
